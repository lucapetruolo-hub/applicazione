import { chromium } from "playwright";
const [,, out] = process.argv;
const b = await chromium.launch({executablePath:"/opt/pw-browsers/chromium",args:["--no-sandbox"]});
const ctx = await b.newContext({viewport:{width:390,height:740},isMobile:true,hasTouch:true,deviceScaleFactor:2});
await ctx.addInitScript((t)=>{ localStorage.setItem("professionisti_token", t); localStorage.setItem("cookie-consent-v1","denied"); }, process.env.TOK);
const p = await ctx.newPage();
await p.clock.setFixedTime(new Date("2026-10-29T06:30:00Z"));
await p.goto("http://localhost:3000/dashboard/agenda", { waitUntil: "networkidle", timeout: 180000 });
await p.waitForTimeout(2000);
await p.selectOption(".ag-view-select select", "week"); await p.waitForTimeout(800);
await p.evaluate(()=>window.scrollTo(0, 330)); await p.waitForTimeout(600);
await p.screenshot({ path: out });
await b.close();
